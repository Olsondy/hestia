import {build} from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const root=fileURLToPath(new URL('../',import.meta.url));
const prototypeRoot=path.join(root,'example/prototypes/projects');
const result=await build({absWorkingDir:root,entryPoints:['example/prototypes/projects/src/app.js'],bundle:true,format:'iife',target:'es2022',minify:true,legalComments:'inline',write:false});
const readText=file=>fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n');
const template=readText(path.join(prototypeRoot,'src/index.html'));
const fontRoot=path.join(root,'assets/fonts/tsanger-yuyang');
const fonts=JSON.parse(fs.readFileSync(path.join(fontRoot,'sources.json'),'utf8'));
const fontCss=fonts.map(f=>`@font-face{font-family:'${f.family}';font-style:normal;font-weight:${f.weight};font-display:swap;src:url(data:font/${f.format==='woff2'?'woff2':'ttf'};base64,${fs.readFileSync(path.join(fontRoot,f.file)).toString('base64')}) format('${f.format}');}`).join('\n');
const fontLicenses=readText(path.join(fontRoot,'NOTICE.txt'));
const css=fontCss+'\n'+readText(path.join(prototypeRoot,'src/style.css'));
const require=createRequire(import.meta.url),threeRoot=path.resolve(path.dirname(require.resolve('three')),'..');
const license=readText(path.join(threeRoot,'LICENSE'));
const html=template.replace('/* STUDIO_STYLE */',()=>css).replace('/* STUDIO_APP */',()=>`/* Three.js\n${license}\nDisplay fonts\n${fontLicenses}\n*/\n${result.outputFiles[0].text.replace(/<\/script/gi,'<\\/script')}`);
fs.writeFileSync(path.join(prototypeRoot,'index.html'),html);
fs.mkdirSync(path.join(root,'dist'),{recursive:true});fs.writeFileSync(path.join(root,'dist/index.html'),html);console.log(`Built example/prototypes/projects/index.html and dist/index.html (${(Buffer.byteLength(html)/1024/1024).toFixed(2)} MB each)`);
